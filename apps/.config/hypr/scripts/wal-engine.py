def write_rofi(p, out=CACHE / "colors-rofi.rasi"):
    """
    Already wired into ~/.config/rofi/config.rasi via:
    @import "~/.cache/wal/colors-rofi.rasi"
    (placed after @theme, so it overrides colors.rasi's hardcoded defaults)
    Variable names match this user's colors.rasi exactly: main-fg, main-bg,
    main-br, active-bg, active-fg, secondary-bg, urgent-color.
    """
    main_bg = p["bg"].lstrip("#") + "dd"      # preserve ~87% opacity from the original
    active_bg = p["accent"].lstrip("#") + "dd"
    secondary_bg = p["tier1"].lstrip("#") + "ee"  # ~93% opacity, slightly more solid

    rasi = f"""/* Generated by wal-engine.py — do not edit directly */
* {{
    main-fg:       {p['fg']};
    main-bg:       #{main_bg};
    main-br:       {p['fg']};

    active-bg:     #{active_bg};
    active-fg:     {p['fg_on_accent']};

    secondary-bg:  #{secondary_bg};
    urgent-color:  {p['critical']};
}}
"""
    out.write_text(rasi)
    print(f"wrote {out}")



def write_swaync(p, out=CACHE / "colors-swaync.css"):
    """
    Import in ~/.config/swaync/style.css with:
    @import url("file:///home/USER/.cache/wal/colors-swaync.css");
    Variable names match this user's existing style.css comments exactly
    (main-bg/main-fg/main-br/active-bg/hover-bg/critical/workspaces/surface/module-fg),
    so the actual hardcoded hex values in that file can be swapped for these.
    """
    module_fg = step(p["critical"], 0.15)  # a lightened "pressed" variant of critical,
                                            # not tied to bg brightness direction
    css = f"""/* Generated by wal-engine.py — do not edit directly */

@define-color main-bg     {p['bg']};
@define-color main-fg     {p['fg']};
@define-color main-br     {p['fg']};
@define-color active-bg   {p['accent']};
@define-color hover-bg    {p['hover']};
@define-color critical    {p['critical']};
@define-color workspaces  {p['tier1']};
@define-color surface     {p['tier2']};
@define-color module-fg   {module_fg};
"""
    out.write_text(css)
    print(f"wrote {out}")



def write_hyprlock(p, wallpaper, template_path=None, out=None):
    """
    Renders ~/.config/hypr/hyprlock.conf.template into the real
    ~/.config/hypr/hyprlock.conf, substituting color and wallpaper tokens.
    No reload needed — hyprlock reads its config fresh each time it's invoked.
    """
    template_path = template_path or (HOME / ".config" / "hypr" / "hyprlock.conf.template")
    out = out or (HOME / ".config" / "hypr" / "hyprlock.conf")

    if not template_path.exists():
        print(f"skipped hyprlock: no template at {template_path}")
        return

    bg_r, bg_g, bg_b = hex_to_rgb255(p["bg"])
    fg_r, fg_g, fg_b = hex_to_rgb255(p["fg"])

    text = template_path.read_text()
    text = (text
            .replace("{{WALLPAPER}}", str(wallpaper))
            .replace("{{BG_R}}", str(bg_r)).replace("{{BG_G}}", str(bg_g)).replace("{{BG_B}}", str(bg_b))
            .replace("{{FG_R}}", str(fg_r)).replace("{{FG_G}}", str(fg_g)).replace("{{FG_B}}", str(fg_b)))

    out.write_text(text)
    print(f"wrote {out}")


