#!/usr/bin/env python3
"""
wal-engine.py — reads pywal's colors.json and writes themed config files for
every integrated app, from one consistently-computed palette.

Usage: wal-engine.py /path/to/current/wallpaper.jpg
(reads ~/.cache/wal/colors.json, which `wal -i` must have already generated)
"""
import json
import sys
import colorsys
from pathlib import Path

HOME = Path.home()
CACHE = HOME / ".cache" / "wal"


# ---------- color math ----------

def hex_to_rgb01(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i+2], 16) / 255 for i in (0, 2, 4))


def hex_to_rgb255(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))


def rgb01_to_hex(r, g, b):
    return "#{:02x}{:02x}{:02x}".format(
        round(max(0, min(1, r)) * 255),
        round(max(0, min(1, g)) * 255),
        round(max(0, min(1, b)) * 255),
    )


def relative_luminance(hex_color):
    r, g, b = hex_to_rgb01(hex_color)

    def lin(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast_ratio(hex_a, hex_b):
    la, lb = relative_luminance(hex_a), relative_luminance(hex_b)
    lighter, darker = max(la, lb), min(la, lb)
    return (lighter + 0.05) / (darker + 0.05)


def step(hex_color, delta):
    r, g, b = hex_to_rgb01(hex_color)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l = max(0.0, min(1.0, l + delta))
    return rgb01_to_hex(*colorsys.hls_to_rgb(h, l, s))


def readable_on(bg_hex, candidates, min_contrast=4.5):
    """Pick the first candidate with enough contrast against bg_hex, else the best of them."""
    best, best_ratio = candidates[0], 0
    for c in candidates:
        ratio = contrast_ratio(c, bg_hex)
        if ratio >= min_contrast:
            return c
        if ratio > best_ratio:
            best, best_ratio = c, ratio
    return best


# ---------- build the palette ----------

def build_palette():
    with open(CACHE / "colors.json") as f:
        data = json.load(f)

    bg = data["special"]["background"]
    fg = data["special"]["foreground"]
    cursor = data["special"].get("cursor", fg)
    c = data["colors"]

    MIN_CONTRAST = 4.5
    if contrast_ratio(fg, bg) < MIN_CONTRAST:
        fg = c["color15"] if contrast_ratio(c["color15"], bg) >= MIN_CONTRAST else "#f2f2f2"

    _, base_l, _ = colorsys.rgb_to_hls(*hex_to_rgb01(bg))
    sign = 1 if base_l < 0.5 else -1

    p = {
        "bg": bg,
        "fg": fg,
        "cursor": cursor,
        "tier1": step(bg, sign * 0.05),
        "tier2": step(bg, sign * 0.10),
        "tier3": step(bg, sign * 0.16),
        "hover": step(bg, sign * 0.20),
        "accent": c["color4"],
        "good": c["color2"],
        "warning": c["color3"],
        "critical": c["color1"],
        "white": c["color15"],
        "black": c["color0"],
        "raw": c,  # full color0-15 dict, for apps that want the whole palette
    }
    p["fg_on_accent"] = readable_on(p["accent"], [p["black"], p["white"]])
    p["fg_on_critical"] = readable_on(p["critical"], [p["black"], p["white"]])
    return p


